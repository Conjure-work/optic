def _routes(app) -> Iterable[Any]:
    """The app's routes, flattened: an included router (FastAPI 0.16x keeps them as _IncludedRouter) is walked."""
    def flat(routes):
        for r in routes:
            if hasattr(r, "effective_route_contexts"):
                yield from flat(list(r.effective_route_contexts()))
            else:
                yield r
    return flat(app.routes)


def pairs(app) -> List[Tuple[str, str, Any]]:
    """(method, path, endpoint or None) for every route the app serves, HEAD folded into GET; a mount is "*"."""
    out = []
    for r in _routes(app):
        endpoint = getattr(r, "endpoint", None)
        methods = getattr(r, "methods", None)
        if endpoint is None or methods is None:                   # a mount: the static files
            out.append(("*", getattr(r, "path", "") or "/", None))
            continue
        for m in sorted(methods):
            if m != "HEAD" or methods == {"HEAD"}:
                out.append((m, r.path, endpoint))
    return sorted(set(out), key=lambda x: (x[1], x[0]))


_CALL = re.compile(r"\b([A-Za-z_]\w*)(?:\.([A-Za-z_]\w*))?\s*\(")


def _key(fn) -> Optional[Tuple[str, str]]:
    fn = inspect.unwrap(fn)
    mod, name = getattr(fn, "__module__", None), getattr(fn, "__name__", None)
    return (mod, name) if mod and name else None


def _resolve(fn, name: str, attr: Optional[str]):
    g = getattr(inspect.unwrap(fn), "__globals__", {})
    obj = g.get(name)
    if obj is None:
        return None
    if attr:
        if isinstance(obj, (types.ModuleType, type)):
            return getattr(obj, attr, None)
        return None
    return obj


def guards_of(fn, depth: int = 0, seen=None) -> Tuple[List[Tuple[str, str]], bool]:
    """The guards `fn` calls, each with the helper it was reached through, and whether CSRF is checked."""
    seen = set() if seen is None else seen
    key = _key(fn)
    if key in seen:
        return [], False
    seen.add(key)
    try:
        src = inspect.getsource(inspect.unwrap(fn))
    except (OSError, TypeError):
        return [], False
    found: List[Tuple[str, str]] = []
    csrf = False
    for pattern, (label, _) in SOURCE_GUARDS.items():
        if re.search(pattern, src):
            found.append((label, "" if depth == 0 else key[1]))
    for name, attr in _CALL.findall(src):
        obj = _resolve(fn, name, attr or None)
        if obj is None or not callable(obj):
            continue
        k = _key(obj)
        if k is None:
            continue
        if k in GUARDS:
            found.append((k[1], "" if depth == 0 else key[1]))
        elif k == CSRF:
            csrf = True
        elif k[0].startswith("app.") and depth < DEPTH and inspect.isfunction(inspect.unwrap(obj)):
            sub, sub_csrf = guards_of(obj, depth + 1, seen)
            found += [(g, via or k[1]) for g, via in sub]
            csrf = csrf or sub_csrf
    uniq = []
    for f in found:
        if f[0] not in [u[0] for u in uniq]:
            uniq.append(f)
    return uniq, csrf


def public_index() -> Dict[str, str]:
    idx: Dict[str, str] = {}
    for reason, lines in PUBLIC.items():
        for line in lines:
            if line in idx:
                raise ValueError("{} is listed twice in PUBLIC".format(line))
            idx[line] = reason
    return idx


def inventory(app) -> Dict[str, Any]:
    """Every route classed: guarded (with its guard), public (with its reason), or unclassified."""
    idx = public_index()
    rows, served = [], set()
    for method, path, endpoint in pairs(app):
        line = "{} {}".format(method, path)
        served.add(line)
        found, csrf = guards_of(endpoint) if endpoint is not None else ([], False)
        if found:
            rows.append({"line": line, "class": "guarded", "guards": found, "csrf": csrf,
                         "listed_public": line in idx})
        elif line in idx:
            rows.append({"line": line, "class": "public", "reason": idx[line], "csrf": csrf})
        else:
            rows.append({"line": line, "class": "unclassified", "csrf": csrf})
    return {"rows": rows, "stale_public": sorted(set(idx) - served)}


def markdown(app) -> str:
    inv = inventory(app)
    rows = inv["rows"]
    guarded = [r for r in rows if r["class"] == "guarded"]
    public = [r for r in rows if r["class"] == "public"]
    out = [START, "",
           "Generated from the app's route table by `tests/support/guard_inventory.py`; `tests/test_guard_inventory.py` "
           "fails on any route that is neither guarded nor public with a reason, and on any difference from this table.",
           "",
           "{} route-method pairs: {} guarded, {} public, {} unclassified.".format(
               len(rows), len(guarded), len(public), len(rows) - len(guarded) - len(public)),
           "", "### The guards", "", "| Guard | Requires |", "| --- | --- |"]
    for (mod, name), what in GUARDS.items():
        out.append("| `{}.{}` | {} |".format(mod, name, what))
    for label, what in SOURCE_GUARDS.values():
        out.append("| `{}` | {} |".format(label, what))
    out += ["", "### Guarded routes", "", "| Route | Guard | Reached through | CSRF on the write |", "| --- | --- | --- | --- |"]
    for r in guarded:
        g = ", ".join("`{}`".format(n) for n, _ in r["guards"])
        via = ", ".join(sorted({"`{}`".format(v) for _, v in r["guards"] if v})) or "the endpoint"
        out.append("| `{}` | {} | {} | {} |".format(r["line"], g, via, "yes" if r["csrf"] else "no"))
    out += ["", "### Public routes, by reason", ""]
    by: Dict[str, List[str]] = {}
    for r in public:
        by.setdefault(r["reason"], []).append(r["line"])
    for reason in PUBLIC:
        if reason in by:
            out.append("- **{}** ({}): {}".format(reason, len(by[reason]), ", ".join("`{}`".format(x) for x in by[reason])))
    out += ["", END]
    return "\n".join(out)


def section_in(text: str) -> Optional[str]:
    if START not in text or END not in text:
        return None
    return text[text.index(START):text.index(END) + len(END)]


def main(argv: List[str]) -> None:
    from app.main import app
    md = markdown(app)
    if argv[:1] == ["--write"]:
        text = TESTING.read_text()
        old = section_in(text)
        if old is None:
            raise SystemExit("TESTING.md has no guard-inventory markers")
        TESTING.write_text(text.replace(old, md))
        print("TESTING.md: guard inventory rewritten")
        return
    if argv[:1] == ["--unclassified"]:
        for r in inventory(app)["rows"]:
            if r["class"] == "unclassified":
                print(r["line"])
        return
    print(md)


if __name__ == "__main__":
    main(sys.argv[1:])
